// Extract designed structural contours from the SAME source as the GLB.
// No tile ribs, brick textures, mural surfaces or invented architecture.
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
const directory = new URL('./', import.meta.url);
const preview = fs.readFileSync(new URL('水龙祠-交互预览.html', directory), 'utf8');
const core = JSON.parse(preview.match(/const coreURL=URL\.createObjectURL\(new Blob\(\[("(?:\\.|[^"\\])*")\]/s)[1]);
const moduleLine = preview.split('\n').find(line => line.startsWith('const moduleText='));
const moduleSource = JSON.parse(moduleLine.slice('const moduleText='.length, moduleLine.lastIndexOf('".replaceAll(') + 1));
const url = text => `data:text/javascript;base64,${Buffer.from(text).toString('base64')}`;
const T = await import(url(moduleSource.replaceAll('./three.core.js', url(core))));
const source = fs.readFileSync(new URL('model-source.js', directory), 'utf8');
const root = new Function('T', `${source}\nreturn makeTemple(T);`)(T);
root.updateMatrixWorld(true);
const layers = Object.fromEntries(['hall','west','east','stage','entrance','roof','timber','court'].map(key => [key, []]));
const names = {'03_MainHall':'hall','04_WestGallery':'west','05_EastGallery':'east','06_Stage':'stage','07_Entrance':'entrance','02_Enclosure':'court'};
const append = (key, a, b, matrix) => {
  a.applyMatrix4(matrix); b.applyMatrix4(matrix);
  layers[key].push(...a.toArray(), ...b.toArray());
};
for (const group of root.children) {
  const key = names[group.name];
  if (!key) continue;
  for (const mesh of group.children) {
    const g = mesh.geometry, kind = mesh.material.userData.texture;
    if (g.type === 'TubeGeometry') {
      // Model roof ridges/eaves/hips and entrance arches only. Exclude tile ribs.
      if (g.parameters.radius < .06) continue;
      const points = g.parameters.path.getPoints(kind === 'roof' ? 12 : 10);
      for (let i = 1; i < points.length; i++) append(kind === 'roof' ? 'roof' : key, points[i-1].clone(), points[i].clone(), mesh.matrixWorld);
    } else if (kind === 'roof') continue;
    else if (g.type === 'CylinderGeometry' && kind === 'wood') {
      // Two longitudinal edges describe each column; omit the polygon rings.
      const {radiusTop, radiusBottom, height} = g.parameters;
      for (let i = 0; i < 2; i++) {
        const a = i * Math.PI;
        append('timber', new T.Vector3(Math.sin(a)*radiusBottom,-height/2,Math.cos(a)*radiusBottom), new T.Vector3(Math.sin(a)*radiusTop,height/2,Math.cos(a)*radiusTop), mesh.matrixWorld);
      }
    } else if (g.type === 'BoxGeometry' || kind === 'brick' || kind === 'plaster') {
      if (kind === 'wood' && g.type === 'BoxGeometry' && Math.min(g.parameters.width,g.parameters.height,g.parameters.depth)<.025) continue;
      if (kind === 'wood' && g.type === 'BoxGeometry') {
        const size=[g.parameters.width,g.parameters.height,g.parameters.depth];
        const longest=size.indexOf(Math.max(...size));
        if(size.filter(n=>n<.3).length===2){
          const a=new T.Vector3(),b=new T.Vector3();a.setComponent(longest,-size[longest]/2);b.setComponent(longest,size[longest]/2);
          append('timber',a,b,mesh.matrixWorld);continue;
        }
      }
      const edges = new T.EdgesGeometry(g, 40), position = edges.getAttribute('position');
      for (let i = 0; i < position.count; i += 2) {
        const a = new T.Vector3().fromBufferAttribute(position, i), b = new T.Vector3().fromBufferAttribute(position, i+1);
        // Arch spandrels contain strip joins: they are not structural outlines.
        if(key==='entrance'&&g.type==='BufferGeometry'&&Math.abs(a.x-b.x)<.001&&Math.abs(a.z-b.z)<.001)continue;
        if (a.distanceTo(b) >= .85) append(kind === 'wood' ? 'timber' : key, a, b, mesh.matrixWorld);
      }
      edges.dispose();
    }
  }
}
// Collapse coincident front/back material boundaries and order bottom → top.
for (const key of Object.keys(layers)) {
  const segments = [], seen = new Set();
  for (let i = 0; i < layers[key].length; i += 6) {
    const segment = layers[key].slice(i, i+6).map(n => Math.round(n*1000)/1000);
    const id = [segment.slice(0,3).join(','), segment.slice(3).join(',')].sort().join('|');
    if (!seen.has(id)) { seen.add(id); segments.push(segment); }
  }
  segments.sort((a,b) => (a[1]+a[4])-(b[1]+b[4]) || a[2]-b[2] || a[0]-b[0]);
  layers[key] = segments.flat();
}
const destination = new URL('a01-lines-data.mjs', directory);
fs.writeFileSync(destination, `// Generated by build-a01-lines.mjs from model-source.js; design contours, not survey data.\nexport const ARCHITECTURE_LINES = ${JSON.stringify(layers)};\n`);
console.log(`A01 contours: ${Object.values(layers).reduce((n,p)=>n+p.length/6,0)} segments; ${fs.statSync(fileURLToPath(destination)).size} bytes.`);
// The standalone offline preview must use the same small, dependency-free layer.
let updated = fs.readFileSync(new URL('水龙祠-交互预览.html', directory), 'utf8');
for (const [name, file] of [['inlineA01Data','a01-lines-data.mjs'],['inlineA01Lines','a01-lines.mjs']]) {
  const declaration = `const ${name}=${JSON.stringify(fs.readFileSync(new URL(file,directory),'utf8'))};`;
  const expression = new RegExp(`^const ${name}="(?:\\\\.|[^"\\\\])*";\\r?$`, 'm');
  updated = expression.test(updated) ? updated.replace(expression, () => declaration) : updated.replace('const localModule=', `${declaration}\nconst localModule=`);
}
fs.writeFileSync(new URL('水龙祠-交互预览.html', directory), updated);
